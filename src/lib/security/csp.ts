// Construye una CSP estricta para un nonce dado. Next.js lee el nonce del header
// Content-Security-Policy de la petición y lo aplica a sus propios scripts.
export const buildCsp = (nonce: string, isDev: boolean) =>
  [
    "default-src 'self'",
    `script-src 'self' 'nonce-${nonce}' 'strict-dynamic'${isDev ? " 'unsafe-eval'" : ""}`,
    // React y Motion escriben atributos style en línea; los scripts siguen siendo estrictos.
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' blob: data:",
    "font-src 'self'",
    `connect-src 'self'${isDev ? " ws:" : ""}`,
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
    ...(isDev ? [] : ["upgrade-insecure-requests"]),
  ].join("; ");
